import { test, expect } from '@playwright/test'
test.skip(process.env.S4_BROWSER_FIXTURE !== 'true', 'requires isolated S4 accounts and simulation mode')

test('subscription, write-only Feishu settings, simulated delivery and mobile revision protection', async ({ browser, baseURL }) => {
  const desktopContext = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } })
  const mobileContext = await browser.newContext({ baseURL, viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const otherContext = await browser.newContext({ baseURL })
  const adminContext = await browser.newContext({ baseURL })
  const desktop = await desktopContext.newPage(), mobile = await mobileContext.newPage(), other = await otherContext.newPage(), admin = await adminContext.newPage(), errors: string[] = []
  for (const page of [desktop, mobile, other, admin]) page.on('pageerror', error => errors.push(error.message))
  const login = async (page: typeof desktop, name: string) => {
    await page.goto('/login'); await page.getByLabel('账号', { exact: true }).fill(name)
    await page.getByLabel('密码', { exact: true }).fill(process.env.S2_BROWSER_PASSWORD!)
    await page.getByRole('button', { name: '登录', exact: true }).click(); await expect(page).toHaveURL(/\/jobs$/)
    await page.goto('/notifications'); await expect(page.getByRole('heading', { name: '订阅与通知', exact: true })).toBeVisible()
  }
  try {
    await login(desktop, 'notify-user-a')
    await expect(desktop.getByText('当前为模拟验收模式：仅保留站内结果，不向真实群发送消息。')).toBeVisible()
    await desktop.getByLabel('岗位关键词', { exact: true }).fill('Go')
    await desktop.getByRole('combobox', { name: '招聘类型', exact: true }).selectOption('campus')
    await desktop.getByLabel('启用我的订阅', { exact: true }).check()
    await desktop.getByRole('button', { name: '保存订阅', exact: true }).click()
    await expect(desktop.getByRole('status')).toContainText('订阅已保存')
    await expect(desktop.getByRole('option', { name: '按当前简历的有效匹配结果订阅（VIP）' })).toHaveJSProperty('disabled', true)
    await desktop.getByLabel('飞书机器人 Webhook', { exact: true }).fill('https://open.feishu.cn/open-apis/bot/v2/hook/11111111-1111-1111-1111-111111111111')
    await desktop.getByLabel('机器人签名密钥（可选）', { exact: true }).fill('isolated-signing-secret')
    await desktop.getByLabel('启用飞书接收', { exact: true }).check()
    await desktop.getByRole('button', { name: '保存接收配置', exact: true }).click()
    await expect(desktop.getByLabel('飞书机器人 Webhook', { exact: true })).toHaveValue('')
    await expect(desktop.getByLabel('机器人签名密钥（可选）', { exact: true })).toHaveValue('')
    await desktop.getByRole('button', { name: '模拟连接测试', exact: true }).click()
    await expect(desktop.locator('.notification-batch').first()).toContainText('模拟完成，未发送到群', { timeout: 20000 })
    await login(other, 'notify-user-b')
    await expect(other.getByText('还没有摘要。保存并启用订阅后，可在这里查看新机会、来源更新情况和发送结果。')).toBeVisible()
    await expect(other.getByRole('button', { name: '模拟连接测试', exact: true })).toBeDisabled()
    await login(mobile, 'notify-user-a')
    await expect(mobile.getByLabel('岗位关键词', { exact: true })).toHaveValue('Go')
    await mobile.getByLabel('启用我的订阅', { exact: true }).uncheck()
    await mobile.getByRole('button', { name: '保存订阅', exact: true }).click()
    await expect(mobile.getByRole('status')).toContainText('订阅已保存')
    await desktop.getByRole('button', { name: '保存订阅', exact: true }).click()
    await expect(desktop.getByRole('status')).toContainText('其他设备')
    expect(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false)
    await expect(mobile.getByRole('navigation', { name: '手机导航' }).getByRole('link', { name: '订阅通知', exact: true })).toBeVisible()
    await desktop.screenshot({ path: test.info().outputPath('desktop-notifications.png'), fullPage: true })
    await mobile.screenshot({ path: test.info().outputPath('mobile-notifications.png'), fullPage: true })
    await login(admin, 'web-admin')
    const choices = await (await adminContext.request.get('/api/v1/jobs/filters')).json()
    if (choices.source_names['nsfocus-campus']) {
      await expect(admin.getByRole('combobox', { name: '要更新的来源' }).getByRole('option', { name: choices.source_names['nsfocus-campus'], exact: true })).toHaveCount(1)
    }
    await admin.getByRole('combobox', { name: '查看账号的发送记录' }).selectOption({ label: 'notify-user-a' })
    await expect(admin.locator('.notification-batch').first()).toContainText('模拟完成，未发送到群')
    expect(errors).toEqual([])
  } finally { await Promise.allSettled([desktopContext.close(), mobileContext.close(), otherContext.close(), adminContext.close()]) }
})
