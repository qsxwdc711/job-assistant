import { test, expect, type Page } from '@playwright/test'
import type { Application } from '../../src/shared/api/types'

const password = process.env.S2_BROWSER_PASSWORD
test.describe.configure({ mode: 'serial' })
async function login(page: Page, username: string) {
  if (!password) throw new Error('S2_BROWSER_PASSWORD is required for the dedicated browser fixture')
  await page.goto('/login')
  await page.getByLabel('账号', { exact: true }).fill(username)
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '下一份机会，认真挑选。' })).toBeVisible()
}

test('desktop and phone preserve URL filters, isolate owners and handle conflicting edits', async ({ browser, baseURL }) => {
  const desktopContext = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 }, timezoneId: 'Asia/Shanghai' })
  const mobileContext = await browser.newContext({ baseURL, viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, timezoneId: 'Asia/Shanghai' })
  const otherContext = await browser.newContext({ baseURL, viewport: { width: 1280, height: 900 }, timezoneId: 'Asia/Shanghai' })
  const errors: string[] = []
  const desktop = await desktopContext.newPage(), mobile = await mobileContext.newPage(), other = await otherContext.newPage()
  for (const page of [desktop, mobile, other]) page.on('pageerror', error => errors.push(error.message))
  try {
    await login(desktop, 'web-user-a')
    await expect(desktop.getByRole('heading', { name: '后台开发', exact: true })).toBeVisible()
    await desktop.getByRole('button', { name: '表格视图', exact: true }).click()
    await expect(desktop).toHaveURL(/view=table/)
    await desktop.getByLabel('岗位关键词', { exact: true }).fill('没有这种岗位的唯一关键词')
    await desktop.getByRole('button', { name: '搜索', exact: true }).click()
    await expect(desktop.getByRole('heading', { name: '暂时没有匹配的岗位' })).toBeVisible()
    await desktop.getByRole('button', { name: '清除筛选', exact: true }).click()
    await expect(desktop.getByRole('heading', { name: '后台开发', exact: true })).toBeVisible()
    await expect(desktop.getByRole('button', { name: '表格视图', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await desktop.getByRole('button', { name: '收藏 后台开发', exact: true }).click()
    await expect(desktop.getByRole('button', { name: '取消收藏 后台开发', exact: true })).toBeVisible()
    await desktop.getByRole('button', { name: '记录投递', exact: true }).click()
    await expect(desktop.getByRole('button', { name: '查看进度', exact: true })).toBeVisible()
    await desktop.getByRole('navigation', { name: '主导航' }).getByRole('link', { name: '投递管理' }).click()
    await desktop.getByRole('button', { name: '管理进度' }).click()
    await desktop.getByLabel('个人备注').fill('电脑端尚未保存的草稿')
    await login(mobile, 'web-user-a')
    const desktopCookie = (await desktopContext.cookies()).find(cookie => cookie.name === 'ja_session')
    const mobileCookie = (await mobileContext.cookies()).find(cookie => cookie.name === 'ja_session')
    expect(desktopCookie?.value).not.toBe(mobileCookie?.value)
    await mobile.getByRole('button', { name: '筛选', exact: true }).click()
    await mobile.getByLabel('工作地点').selectOption({ label: '深圳市' })
    await mobile.getByRole('button', { name: '应用筛选', exact: true }).click()
    await expect(mobile).toHaveURL(/city=/)
    await expect(mobile.getByRole('heading', { name: '后台开发', exact: true })).toBeVisible()
    await mobile.screenshot({ path: test.info().outputPath('mobile-jobs.png'), fullPage: true })
    await desktop.screenshot({ path: test.info().outputPath('desktop-applications.png'), fullPage: true })
    await mobile.getByRole('navigation', { name: '手机导航' }).getByRole('link', { name: '投递管理' }).click()
    await mobile.getByRole('button', { name: '管理进度' }).click()
    await mobile.getByLabel('当前进度', { exact: true }).selectOption('interview')
    await mobile.getByLabel('下一步事项', { exact: true }).fill('准备并发与项目讲解')
    await mobile.getByLabel('个人备注').fill('手机端已保存的备注')
    await mobile.getByRole('button', { name: '保存进度', exact: true }).click()
    await expect(mobile.getByRole('status')).toContainText('进度已保存')
    await desktop.getByRole('button', { name: '保存进度', exact: true }).click()
    await expect(desktop.getByRole('alert')).toContainText('其他设备修改')
    await expect(desktop.getByLabel('个人备注')).toHaveValue('电脑端尚未保存的草稿')
    await desktop.getByRole('button', { name: '刷新最新记录，保留输入', exact: true }).click()
    await expect(desktop.getByRole('alert')).toContainText('已读取最新版本')
    await expect(desktop.getByLabel('个人备注')).toHaveValue('电脑端尚未保存的草稿')
    await desktop.getByRole('button', { name: '保存进度', exact: true }).click()
    await expect(desktop.getByRole('status')).toContainText('进度已保存')
    const records = await (await desktopContext.request.get('/api/v1/me/applications')).json() as { items: Application[] }
    expect(records.items).toHaveLength(1)
    expect(records.items[0].version).toBe(3)
    await login(other, 'web-user-b')
    expect((await otherContext.request.get('/api/v1/me/applications/' + records.items[0].id)).status()).toBe(404)
    expect((await otherContext.request.get('/api/v1/me/applications/' + records.items[0].id + '/events')).status()).toBe(404)
    expect((await otherContext.request.get('/api/v1/admin/applications')).status()).toBe(403)
    const ownRecords = await (await otherContext.request.get('/api/v1/me/applications')).json()
    expect(ownRecords.total).toBe(0)
    const ownSaved = await (await otherContext.request.get('/api/v1/me/favorites')).json()
    expect(ownSaved.items).toHaveLength(0)
    expect(await desktop.evaluate(() => localStorage.length)).toBe(0)
    expect(errors).toEqual([])
  } finally { await desktopContext.close(); await mobileContext.close(); await otherContext.close() }
})

test('administrator hiding a public job preserves another user’s application', async ({ page }) => {
  await login(page, 'web-admin')
  await page.getByRole('navigation', { name: '主导航' }).getByRole('link', { name: '管理中心' }).click()
  await expect(page.getByRole('heading', { name: '让数据与权限，保持清晰。' })).toBeVisible()
  await page.getByRole('button', { name: '岗位维护', exact: true }).click()
  page.once('dialog', dialog => dialog.accept('独立浏览器测试：保留个人进度'))
  await page.getByRole('button', { name: '隐藏岗位', exact: true }).click()
  await expect(page.getByRole('button', { name: '重新发布', exact: true })).toBeVisible()
  const adminRecords = await (await page.request.get('/api/v1/admin/applications')).json() as {items: Application[]}
  expect(adminRecords.items).toHaveLength(1)
  expect(adminRecords.items[0].job.published).toBe(false)
  expect(adminRecords.items[0].version).toBe(3)
  expect(adminRecords.items[0].notes).toBe('电脑端尚未保存的草稿')
})
